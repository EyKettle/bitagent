// Raw HTTP verifies fixture assets; no model entity, business policy or product host.
test("standalone text fixtures serve HTTP values, limits and failures", { timeout: 15000 }, async (t) => {
  const url = await launchMock(t);
  async function request(prompt) {
    return fetch(url + "/v1/chat/completions", {
      method: "POST", headers: { "content-type": "application/json" },
      body: JSON.stringify({ model: "bitagent-mock", messages: [{ role: "user", content: prompt }], stream: false }),
      signal: AbortSignal.timeout(5000),
    });
  }
  const normal = await request("hello");
  assert.equal(normal.status, 200);
  const value = await normal.json();
  assert.equal(value.choices[0].message.content, "Mock response: generated by a local fixture, not a real model.");
  const limited = await (await request("[length]")).json();
  assert.equal(limited.choices[0].finish_reason, "length");
  assert.equal(limited.choices[0].message.content, "This answer reached the fixture token limit.");
  const summary = await (await request("[summary]")).json();
  assert.equal(summary.choices[0].message.content, await readFile(new URL("../../dev/llmock/payloads/summary.txt", import.meta.url), "utf8"));
  const failed = await request("[error]");
  assert.equal(failed.status, 500);
  await failed.arrayBuffer();
});

test("standalone Messages fixtures expose raw tool payloads and streaming frames", { timeout: 15000 }, async (t) => {
  const url = await launchMock(t, "submit");
  async function request(prompt, stream = false) {
    return fetch(url + "/v1/messages", {
      method: "POST", headers: { "content-type": "application/json", "anthropic-version": "2023-06-01" },
      body: JSON.stringify({ model: "bitagent-submit", max_tokens: 128, messages: [{ role: "user", content: prompt }], stream }),
      signal: AbortSignal.timeout(5000),
    });
  }
  const invalid = await request("[invalid]");
  assert.equal(invalid.status, 200);
  const invalidBody = await invalid.json();
  assert.ok(invalidBody.content.every((block) => typeof block.id === "string"));
  assert.deepEqual(invalidBody.content.map(({ id, ...payload }) => payload), JSON.parse(await readFile(new URL("../../dev/llmock/payloads/submit-invalid.json", import.meta.url), "utf8")));
  const valid = await request("[valid]");
  assert.equal(valid.status, 200);
  const validBody = await valid.json();
  assert.ok(validBody.content.every((block) => typeof block.id === "string"));
  assert.deepEqual(validBody.content.map(({ id, ...payload }) => payload), JSON.parse(await readFile(new URL("../../dev/llmock/payloads/submit-valid.json", import.meta.url), "utf8")));
  const streamed = await request("[valid]", true);
  assert.equal(streamed.status, 200);
  const frames = await streamed.text();
  assert.match(frames, /event: message_start/);
  assert.match(frames, /event: message_stop/);
  assert.match(frames, /after_submit/);
  const failed = await request("[error]");
  assert.equal(failed.status, 500);
  await failed.arrayBuffer();
});
