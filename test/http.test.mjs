import assert from "node:assert/strict";
import { test } from "node:test";
import { createApplication } from "@bitagent/core";
import { createScriptConsole, ScriptCompileError } from "@bitagent/core/node";
import { PiGenerationError } from "@bitagent/core/pi";
import { createMockLlm } from "../examples/mock-llm.mjs";
import { launchMock } from "./support/mock.mjs";

test("the low-level text adapter still works against a loopback LLMock server", { timeout: 30000 }, async (t) => {
  const url = await launchMock(t);
  const llm = createMockLlm(url + "/v1");

  await t.test("fixed response is streamed over HTTP", async () => {
    const chunks = [];
    const result = await llm.generate({ prompt: "hello", onText: (delta) => { chunks.push(delta); } });
    assert.equal(result.text, "Mock response: generated by a local fixture, not a real model.");
    assert.equal(result.finishReason, "stop");
    assert.equal(chunks.join(""), result.text);
  });

  await t.test("HTTP errors and token limits stay distinct", async () => {
    await assert.rejects(llm.generate({ prompt: "[error]" }), PiGenerationError);
    const result = await llm.generate({ prompt: "[length]" });
    assert.equal(result.finishReason, "length");
    assert.equal(result.text, "This answer reached the fixture token limit.");
  });

  await t.test("cancelling live HTTP generation settles the supervised run", async () => {
    const app = createApplication();
    const reason = new Error("cancel HTTP request");
    const run = app.start(({ signal }) => llm.generate({
      prompt: "hello", signal, onText: () => { run.cancel(reason); },
    }));
    assert.deepEqual(await run.done, { status: "cancelled", reason });
  });

  await t.test("a host script can still import the low-level text skill", async () => {
    const app = createApplication();
    const scripts = await createScriptConsole({ app, llm });
    await scripts.evaluate('import { summarize } from "@bitagent/core/skills";');
    await scripts.evaluate('const run = app.start(({ signal }) => summarize(llm, { text: "[summary]", instruction: "Summarize." }, signal));');
    const result = await app.list()[0].done;
    assert.equal(result.status, "succeeded");
    assert.equal(result.value.text, "Programs control the workflow; the language model only generates text.\n");
    assert.equal((await scripts.evaluate("run.state.status")).value, "succeeded");
    await assert.rejects(scripts.evaluate('summarize(llm, { text: 42, instruction: "Summarize." })'), ScriptCompileError);
  });
});
