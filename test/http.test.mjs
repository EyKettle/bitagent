import assert from "node:assert/strict";
import { fork, spawn } from "node:child_process";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import { createApplication } from "@bitagent/core";
import { createScriptConsole, ScriptCompileError } from "@bitagent/core/node";
import { PiGenerationError } from "@bitagent/core/pi";
import { createMockLlm } from "../examples/mock-llm.mjs";

async function launchMock(t) {
  const child = fork(fileURLToPath(new URL("../dev/mock.mjs", import.meta.url)), ["--port", "0"], {
    execArgv: ["--import", "tsx"], silent: true,
  });
  let output = "";
  child.stdout.on("data", (chunk) => { output += chunk; });
  child.stderr.on("data", (chunk) => { output += chunk; });
  const exited = new Promise((resolve) => {
    child.once("exit", (code, signal) => resolve({ code, signal }));
    child.once("error", (error) => resolve({ error }));
  });
  t.after(async () => {
    if (child.connected) child.send("stop");
    const timeout = setTimeout(() => child.kill("SIGKILL"), 5000);
    try { await exited; } finally { clearTimeout(timeout); }
  });
  return new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error("Mock startup timed out: " + output)), 10000);
    const onMessage = (message) => {
      if (message?.type !== "ready" || typeof message.url !== "string") return;
      cleanup();
      resolve(message.url);
    };
    const onExit = (code) => { cleanup(); reject(new Error("Mock exited: " + code + "\n" + output)); };
    const onError = (error) => { cleanup(); reject(error); };
    function cleanup() {
      clearTimeout(timeout);
      child.off("message", onMessage);
      child.off("exit", onExit);
      child.off("error", onError);
    }
    child.on("message", onMessage);
    child.once("exit", onExit);
    child.once("error", onError);
  });
}

test("public package works against a real loopback LLMock server", { timeout: 30000 }, async (t) => {
  const url = await launchMock(t);
  const llm = createMockLlm(url + "/v1");

  await t.test("fixed response is streamed over HTTP", async () => {
    const chunks = [];
    const result = await llm.generate({ prompt: "hello", onText: (delta) => { chunks.push(delta); } });
    assert.equal(result.text, "Mock response: generated by a local fixture, not a real model.");
    assert.equal(result.finishReason, "stop");
    assert.equal(chunks.join(""), result.text);
  });

  await t.test("HTTP errors and token limits stay distinct", async () => {
    await assert.rejects(llm.generate({ prompt: "[error]" }), PiGenerationError);
    const result = await llm.generate({ prompt: "[length]" });
    assert.equal(result.finishReason, "length");
    assert.equal(result.text, "This answer reached the fixture token limit.");
  });

  await t.test("cancelling live HTTP generation settles the supervised run", async () => {
    const app = createApplication();
    const reason = new Error("cancel HTTP request");
    const run = app.start(({ signal }) => llm.generate({
      prompt: "hello", signal, onText: () => { run.cancel(reason); },
    }));
    assert.deepEqual(await run.done, { status: "cancelled", reason });
  });

  await t.test("a user script imports the official skill through its public entry", async () => {
    const app = createApplication();
    const scripts = await createScriptConsole({ app, llm });
    await scripts.evaluate('import { summarize } from "@bitagent/core/skills";');
    await scripts.evaluate('const run = app.start(({ signal }) => summarize(llm, { text: "[summary]", instruction: "Summarize." }, signal));');
    const result = await app.list()[0].done;
    assert.equal(result.status, "succeeded");
    assert.equal(result.value.text, "Programs control the workflow; the language model only generates text.\n");
    assert.equal((await scripts.evaluate("run.state.status")).value, "succeeded");
    await assert.rejects(scripts.evaluate('summarize(llm, { text: 42, instruction: "Summarize." })'), ScriptCompileError);
  });

  await t.test("terminal input retains definitions, awaits HTTP work and explicitly resets", async () => {
    const child = spawn(process.execPath, [
      fileURLToPath(new URL("../examples/console.mjs", import.meta.url)), "--base-url", url + "/v1",
    ], { stdio: ["pipe", "pipe", "pipe"] });
    let output = "";
    let errors = "";
    child.stdout.on("data", (chunk) => { output += chunk; });
    child.stderr.on("data", (chunk) => { errors += chunk; });
    const exited = new Promise((resolve, reject) => {
      child.once("error", reject);
      child.once("close", (code) => resolve(code));
    });
    const timeout = setTimeout(() => child.kill("SIGKILL"), 10000);
    child.stdin.end([
      "function double(n: number) {",
      "return n * 2;",
      "}",
      "const retained = double(21);",
      'console.log("RETENTION", retained);',
      'const run = app.start(({ signal }) => llm.generate({ prompt: "[summary]", signal }));',
      'console.log("OUTCOME", (await run.done).status);',
      ".clear",
      'console.log("AFTER_RESET", app.list().length);',
      "retained",
      'console.log("CONTINUE");',
      'const closing = app.start(async ({ signal }) => { await new Promise<void>(resolve => signal.addEventListener("abort", () => resolve(), { once: true })); signal.throwIfAborted(); });',
      'closing.done.then(outcome => console.log("CLOSED_RUN", outcome.status));',
      ".exit",
      "",
    ].join("\n"));
    let code;
    try { code = await exited; } finally { clearTimeout(timeout); }
    assert.equal(code, 0, output + errors);
    assert.match(output, /RETENTION 42/);
    assert.match(output, /OUTCOME succeeded/);
    assert.match(output, /AFTER_RESET 1/);
    assert.match(output, /Cannot find name 'retained'/);
    assert.match(output, /CONTINUE/);
    assert.match(output, /CLOSED_RUN cancelled/);
    assert.equal(errors, "");
  });
});
