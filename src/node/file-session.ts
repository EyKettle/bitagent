import { closeSync, existsSync, mkdirSync, mkdtempSync, openSync, readFileSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createContext, Script } from "node:vm";
import ts from "typescript";
import type { LLMEntity, Scheduler } from "../index.js";
import { compileFile, FileCompileError, scriptInternals } from "./file-compiler.js";
import type { Binding } from "./file-compiler.js";

export interface Definition {
  readonly name: string;
  readonly source: string;
}

export interface DefinitionScope {
  list(): readonly Definition[];
  /** Removes a name, not references already captured by other definitions or tasks. */
  forget(definition: Definition): boolean;
  clear(): void;
}

export interface FileSessionOptions {
  readonly app: Scheduler;
  readonly llm: LLMEntity;
  readonly cwd?: string;
}

export interface FileEvaluation {
  readonly value: unknown;
  readonly definitions: readonly Definition[];
}

export interface FileSession {
  readonly cwd: string;
  readonly declarationsPath: string;
  readonly scope: DefinitionScope;
  /** Reads, checks and executes one file; it does not wait for tasks started by it. */
  runFile(filename: string): FileEvaluation;
  evaluate(source: string): FileEvaluation;
  /** Releases this workspace's editor connection, without cancelling app tasks. */
  close(): void;
}

interface SavedDefinition extends Binding {
  readonly handle: Definition;
  readonly declaration: string;
  readonly get?: () => unknown;
  readonly set?: (value: unknown) => void;
}

type ModuleValue = { exports: unknown };
const generatedHeader = "// Generated by BitAgent; the live names belong to the running instance.\n";

function modulePath(declaration: string): string {
  return declaration.replace(/\.d\.(ts|cts|mts)$/, (_match, extension: string) =>
    extension === "cts" ? ".cjs" : extension === "mts" ? ".mjs" : ".js");
}

function globalDeclarations(definitions: Iterable<SavedDefinition>, publicEntry: string, nodeEntry: string): string {
  const items = [...definitions];
  const imports = items.map((item, index) => `import * as capture${index} from ${JSON.stringify(modulePath(item.declaration))};`);
  const bindings = items.map((item, index) => item.namespace
    ? (item.typeOnly ? "  // @ts-expect-error TS1380: the ambient alias retains its source's type-only semantics.\n" : "") +
      `  export import ${item.name} = capture${index}.${item.alias};`
    : `  ${item.mutable ? "let" : "const"} ${item.name}: typeof capture${index}.${item.alias};`);
  const nodeTypes = createRequire(import.meta.url).resolve("@types/node/index.d.ts");
  return [generatedHeader, `/// <reference path=${JSON.stringify(nodeTypes)} />`, ...imports, "export {};", "declare global {",
    `  const app: import(${JSON.stringify(publicEntry)}).Scheduler;`,
    `  const llm: import(${JSON.stringify(publicEntry)}).LLMEntity;`,
    `  const scope: import(${JSON.stringify(nodeEntry)}).DefinitionScope;`,
    ...bindings, "}", ""].join("\n");
}

/** Bind old type references to their original declarations, not tomorrow's live globals. */
function pinDeclarations(text: string, filename: string, prior: readonly SavedDefinition[]): string {
  const parsed = ts.createSourceFile(filename, text, ts.ScriptTarget.ES2022, true);
  const local = new Set<string>();
  const record = (name: ts.BindingName) => {
    if (ts.isIdentifier(name)) local.add(name.text);
    else for (const element of name.elements) if (!ts.isOmittedExpression(element)) record(element.name);
  };
  for (const statement of parsed.statements) {
    if (ts.isVariableStatement(statement)) for (const declaration of statement.declarationList.declarations) record(declaration.name);
    else if (ts.isImportDeclaration(statement)) {
      const clause = statement.importClause;
      if (clause?.name) local.add(clause.name.text);
      if (clause?.namedBindings) {
        if (ts.isNamespaceImport(clause.namedBindings)) local.add(clause.namedBindings.name.text);
        else for (const specifier of clause.namedBindings.elements) local.add(specifier.name.text);
      }
    } else if ("name" in statement && statement.name && ts.isIdentifier(statement.name as ts.Node)) {
      local.add((statement.name as ts.Identifier).text);
    }
  }
  const imports = prior.filter((item) => !local.has(item.name)).map((item) =>
    `import { ${item.alias} as ${item.name} } from ${JSON.stringify(modulePath(item.declaration))};`);
  return [...imports, text].join("\n");
}

/** Trusted local TypeScript, not a sandbox or crash-recoverable execution engine. */
export function createFileSession(options: FileSessionOptions): FileSession {
  const cwd = resolve(options.cwd ?? process.cwd());
  const directory = join(cwd, ".bitagent");
  mkdirSync(directory, { recursive: true });
  const lock = join(directory, "session.lock");
  // One editor declaration surface must not silently point at two live instances.
  let descriptor: number;
  try { descriptor = openSync(lock, "wx", 0o600); }
  catch (error) { throw new Error(`Cannot claim ${lock}; another session or a stale lock exists`, { cause: error }); }
  closeSync(descriptor);
  const declarationsPath = join(directory, "globals.d.ts");
  const publicEntry = fileURLToPath(new URL("../index.js", import.meta.url));
  const nodeEntry = fileURLToPath(new URL("./index.js", import.meta.url));
  const definitions = new Map<string, SavedDefinition>();
  let versionDirectory: string;
  try { versionDirectory = mkdtempSync(join(directory, "session-")); }
  catch (error) { unlinkSync(lock); throw error; }
  let version = 0;
  let closed = false;
  let evaluating = false;

  function ensureOpen(): void {
    if (closed) throw new Error("File session is closed");
  }
  function writeDeclarations(content: string): void {
    const temporary = join(versionDirectory, "globals.next.d.ts");
    writeFileSync(temporary, content);
    renameSync(temporary, declarationsPath);
  }
  function syncDeclarations(next: Iterable<SavedDefinition> = definitions.values()): void {
    writeDeclarations(globalDeclarations(next, publicEntry, nodeEntry));
  }
  const scope: DefinitionScope = Object.freeze({
    list: () => Object.freeze([...definitions.values()].map((item) => item.handle)),
    forget(handle: Definition): boolean {
      ensureOpen();
      const definition = definitions.get(handle.name);
      if (definition?.handle !== handle) return false;
      syncDeclarations([...definitions.values()].filter((item) => item !== definition));
      definitions.delete(handle.name);
      return true;
    },
    clear(): void { ensureOpen(); syncDeclarations([]); definitions.clear(); },
  });
  try {
    if (existsSync(declarationsPath) && !readFileSync(declarationsPath, "utf8").startsWith(generatedHeader)) {
      throw new Error(`Refusing to overwrite a non-generated declaration file: ${declarationsPath}`);
    }
    syncDeclarations();
  } catch (error) {
    unlinkSync(lock);
    throw error;
  }

  function execute(filename: string, source: string): FileEvaluation {
    ensureOpen();
    if (evaluating) throw new Error("Nested file evaluation is not supported");
    evaluating = true;
    try {
      const before = [...definitions.values()];
      const output = join(versionDirectory, String(++version));
      const compiled = compileFile(filename, source, declarationsPath, output);
      for (const binding of compiled.bindings) {
        if (["app", "llm", "scope", ...Object.values(scriptInternals)].includes(binding.name) || definitions.has(binding.name)) {
          throw new FileCompileError(`Definition ${binding.name} already exists; explicitly forget it before redefining it`);
        }
      }
      for (const [path, text] of compiled.declarations) {
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, pinDeclarations(text, path, before), { flag: "wx" });
      }
      const created: Definition[] = [];
      const declare = (binding: Binding, get?: () => unknown, set?: (value: unknown) => void) => {
        // Merged namespaces and overloads share one binding and one handle.
        if (definitions.has(binding.name)) return;
        const handle = Object.freeze({ name: binding.name, source: filename });
        definitions.set(binding.name, { ...binding, handle, declaration: compiled.captureFile,
          ...(get === undefined ? {} : { get }), ...(set === undefined ? {} : { set }) });
        created.push(handle);
      };
      for (const binding of compiled.bindings) if (!binding.value && binding.namespace) declare(binding);
      let value: unknown;
      const context = createContext({
        console, process, Buffer, setTimeout, clearTimeout, setInterval, clearInterval, setImmediate, clearImmediate,
        queueMicrotask, structuredClone, performance, AbortController, AbortSignal, DOMException,
        URL, URLSearchParams, TextEncoder, TextDecoder, fetch, Headers, Request, Response, FormData, Blob,
      });
      Object.defineProperties(context, {
        app: { value: options.app, enumerable: true },
        llm: { value: options.llm, enumerable: true },
        scope: { value: scope, enumerable: true },
      });
      for (const item of before) if (item.get) {
        Object.defineProperty(context, item.name, { get: item.get, ...(item.set ? { set: item.set } : {}), enumerable: true });
      }
      context.global = context;
      const cache = new Map<string, ModuleValue>();
      const executeModule = (path: string): unknown => {
        const existing = cache.get(path);
        if (existing) return existing.exports;
        const code = compiled.javascript.get(path);
        if (code === undefined) throw new Error(`No checked output for ${path}`);
        const module: ModuleValue = { exports: {} };
        cache.set(path, module);
        const hostRequire = createRequire(path);
        const requireModule = (specifier: string): unknown => {
          const resolved = compiled.resolutions.get(path)?.get(specifier);
          return resolved && compiled.javascript.has(resolved) ? executeModule(resolved) : hostRequire(specifier);
        };
        const capture = (name: string, get: () => unknown, set?: (next: unknown) => void) => {
          const binding = compiled.bindings.find((candidate) => candidate.name === name && candidate.value);
          if (!binding) throw new Error(`Unexpected captured definition ${name}`);
          declare(binding, get, set);
        };
        const script = new Script(`(function(exports, require, module, __filename, __dirname, ${scriptInternals.captureName}, ${scriptInternals.resultName}) {\n${code}\n})`, { filename: path });
        const run: (...args: unknown[]) => void = script.runInContext(context);
        run(module.exports, requireModule, module, path, dirname(path), capture, (result: unknown) => { value = result; });
        return module.exports;
      };
      try { executeModule(compiled.main); }
      finally { syncDeclarations(); }
      return Object.freeze({ value, definitions: Object.freeze(created.filter((handle) =>
        definitions.get(handle.name)?.handle === handle)) });
    } finally { evaluating = false; }
  }

  return Object.freeze({
    cwd, declarationsPath, scope,
    runFile(filename: string): FileEvaluation {
      const path = resolve(cwd, filename);
      return execute(path, readFileSync(path, "utf8"));
    },
    evaluate(source: string): FileEvaluation { return execute(join(cwd, `[input-${version + 1}].ts`), source); },
    close(): void {
      if (closed) return;
      if (evaluating) throw new Error("Cannot close a file session during evaluation");
      writeDeclarations(generatedHeader + "// No live editor connection. Start a new file session to reconnect.\nexport {};\n");
      unlinkSync(lock);
      closed = true;
    },
  });
}
